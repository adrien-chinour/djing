"""Generate the Mixxx mapping for the agent port from agent/protocol.py.

Writes mixxx/controllers/djing-agent.midi.xml (one <control> per message, all bound
to DjingAgent.cmd) and mixxx/controllers/djing-agent-protocol.js (lookup tables used
by djing-agent-script.js). Run from the project root: python3 -I -m agent.build_mapping
"""

import json
from pathlib import Path

from agent import protocol as p

ROOT = Path(__file__).resolve().parent.parent
XML_OUT = ROOT / "mixxx/controllers/djing-agent.midi.xml"
JS_OUT = ROOT / "mixxx/controllers/djing-agent-protocol.js"


def xml_control(group: str, status: int, num: int, description: str) -> str:
    return f"""\t\t\t<control>
\t\t\t\t<group>{group}</group>
\t\t\t\t<key>DjingAgent.cmd</key>
\t\t\t\t<description>{description}</description>
\t\t\t\t<status>0x{status:02X}</status>
\t\t\t\t<midino>0x{num:02X}</midino>
\t\t\t\t<options>
\t\t\t\t\t<script-binding />
\t\t\t\t</options>
\t\t\t</control>
"""


def main() -> None:
    controls: list[str] = []
    notes: dict[str, dict] = {}
    ccs: dict[str, dict] = {}
    feedback: list[dict] = []

    def add_note(ch: int, cmd: p.NoteCommand, deck: str | None) -> None:
        group = p.resolve_group(cmd.group, deck)
        label = f"{deck or 'master'} {cmd.name}"
        controls.append(xml_control(group, 0x90 | ch, cmd.num, label))
        notes[f"{ch}:{cmd.num}"] = {"group": group, "key": cmd.key, "mode": cmd.mode}

    def add_cc(ch: int, cmd: p.CcCommand, deck: str | None) -> None:
        group = p.resolve_group(cmd.group, deck)
        label = f"{deck or 'master'} {cmd.name} ({cmd.bits}-bit)"
        controls.append(xml_control(group, 0xB0 | ch, cmd.num, label))
        if cmd.bits == 14:
            controls.append(xml_control(group, 0xB0 | ch, cmd.num + p.LSB_OFFSET, label + " LSB"))
        ccs[f"{ch}:{cmd.num}"] = {"group": group, "key": cmd.key, "bits": cmd.bits,
                                 "param": cmd.param, "min": cmd.min, "max": cmd.max}

    def add_feedback(ch: int, fb: p.Feedback, deck: str | None) -> None:
        feedback.append({"group": p.resolve_group(fb.group, deck), "key": fb.key, "kind": fb.kind,
                         "ch": ch, "num": fb.num, "param": fb.param, "scale": fb.scale})

    for deck, ch in p.DECK_CHANNEL.items():
        for cmd in p.DECK_NOTES:
            add_note(ch, cmd, deck)
        for cmd in p.DECK_CCS:
            add_cc(ch, cmd, deck)
        for fb in p.DECK_FEEDBACK:
            add_feedback(ch, fb, deck)
    for cmd in p.MASTER_NOTES:
        add_note(p.MASTER_CHANNEL, cmd, None)
    for cmd in p.MASTER_CCS:
        add_cc(p.MASTER_CHANNEL, cmd, None)
    for fb in p.MASTER_FEEDBACK:
        add_feedback(p.MASTER_CHANNEL, fb, None)
    controls.append(xml_control("[Master]", 0x90 | p.MASTER_CHANNEL, p.RESYNC_NOTE, "agent asks for a full state resend"))

    xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<MixxxMIDIPreset mixxxVersion="2.4" schemaVersion="1">
\t<info>
\t\t<name>djing agent (virtual MIDI)</name>
\t\t<author>djing project</author>
\t\t<description>Generated from agent/protocol.py: commands from the agent, state feedback to it. Do not edit by hand.</description>
\t</info>
\t<controller id="djing-agent">
\t\t<scriptfiles>
\t\t\t<file filename="djing-agent-protocol.js" />
\t\t\t<file functionprefix="DjingAgent" filename="djing-agent-script.js" />
\t\t</scriptfiles>
\t\t<controls>
{''.join(controls)}\t\t</controls>
\t\t<outputs/>
\t</controller>
</MixxxMIDIPreset>
"""
    XML_OUT.write_text(xml, encoding="utf-8")
    table = {"notes": notes, "ccs": ccs, "feedback": feedback,
             "masterChannel": p.MASTER_CHANNEL, "helloNote": p.HELLO_NOTE, "resyncNote": p.RESYNC_NOTE, "lsbOffset": p.LSB_OFFSET}
    JS_OUT.write_text("// Generated by agent/build_mapping.py from agent/protocol.py. Do not edit.\n"
                      "var DjingAgentProtocol = " + json.dumps(table, indent=2) + ";\n", encoding="utf-8")
    print(f"wrote {XML_OUT.relative_to(ROOT)} ({len(controls)} controls) and {JS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
